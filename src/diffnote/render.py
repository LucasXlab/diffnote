"""Output renderers: terminal (ANSI), markdown (PR body), json."""

import json as _json

RESET = "\033[0m"
BOLD = "\033[1m"
DIM = "\033[2m"
GREEN = "\033[32m"
RED = "\033[31m"
YELLOW = "\033[33m"
CYAN = "\033[36m"
MAGENTA = "\033[35m"


def _c(text, code, use_color):
    return f"{code}{text}{RESET}" if use_color else text


def render_terminal(summary, use_color=True, llm_prose=None):
    out = []
    bar = "─" * 42
    out.append(_c("diffnote", BOLD + CYAN, use_color) +
               _c(" — PR / changelog summary", DIM, use_color))
    out.append(_c(bar, DIM, use_color))
    out.append(_c(f"  {summary['total_files']} files changed  ", BOLD, use_color) +
               _c(f"(+{summary['added']} / -{summary['deleted']})", GREEN if False else "", use_color))
    out.append(_c("  Suggested title: ", BOLD, use_color) +
               _c(summary["title"], YELLOW, use_color))
    out.append(_c("  Changelog section: ", BOLD, use_color) +
               _c(summary["section"], CYAN, use_color))

    if summary["risks"]:
        out.append("")
        out.append(_c("  Risk signals", BOLD + YELLOW, use_color))
        for r in summary["risks"]:
            out.append(_c(f"   • {r['label']} ", YELLOW, use_color) +
                       _c(f"({len(r['files'])})", DIM, use_color))
            for fp in r["files"][:4]:
                out.append(_c(f"       - {fp}", DIM, use_color))

    out.append("")
    out.append(_c("  Changes by area", BOLD, use_color))
    for area, count in sorted(summary["areas"].items(), key=lambda x: -x[1]):
        out.append(f"   {area:<10} {count}")

    out.append("")
    out.append(_c("  Highlights", BOLD, use_color))
    for h in summary["highlights"]:
        sign = f"+{h['added']} -{h['deleted']}"
        extra = ("  ⚠ " + "; ".join(h["risks"])) if h["risks"] else ""
        out.append(_c(f"   • {h['path']} ", CYAN, use_color) +
                   _c(f"[{h['status']}] ", DIM, use_color) +
                   _c(sign, GREEN if h["added"] >= h["deleted"] else RED, use_color) +
                   _c(extra, YELLOW, use_color))

    if llm_prose:
        out.append("")
        out.append(_c("  Summary (local LLM)", BOLD + MAGENTA, use_color))
        for line in llm_prose.splitlines():
            out.append("   " + line)

    out.append(_c(bar, DIM, use_color))
    out.append(_c("  Generated by diffnote (offline). "
                  "Add --llm for a prose summary via local Ollama.", DIM, use_color))
    return "\n".join(out)


def render_markdown(summary, llm_prose=None):
    lines = []
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- **{summary['title']}**")
    lines.append(f"- Changelog section: `{summary['section']}`")
    lines.append(f"- {summary['total_files']} files changed (+{summary['added']} / -{summary['deleted']})")
    if llm_prose:
        lines.append("")
        lines.append(llm_prose)
    lines.append("")
    if summary["risks"]:
        lines.append("## Risk signals")
        lines.append("")
        for r in summary["risks"]:
            lines.append(f"- **{r['label']}** ({len(r['files'])})")
            for fp in r["files"][:5]:
                lines.append(f"  - `{fp}`")
        lines.append("")
    lines.append("## Changes")
    lines.append("")
    lines.append("| File | Status | + | - | Area |")
    lines.append("|------|--------|---|---|------|")
    for h in summary["highlights"]:
        lines.append(f"| `{h['path']}` | {h['status']} | {h['added']} | {h['deleted']} | {h['area']} |")
    if len(summary["highlights"]) < summary["total_files"]:
        lines.append(f"| … and {summary['total_files'] - len(summary['highlights'])} more | | | | |")
    lines.append("")
    lines.append("_Generated by [diffnote](https://github.com/LucasYanzy/diffnote) — offline-first._")
    return "\n".join(lines)


def render_json(summary, llm_prose=None):
    data = dict(summary)
    if llm_prose:
        data["llm_summary"] = llm_prose
    return _json.dumps(data, indent=2, ensure_ascii=False)
